export const FONT_CHARS = Object.keys(GLYPHS);

/** The glyph's rows (7 strings of 5 chars), or null if the font has no such character. */
export function glyph(ch: string): string[] | null {
  const g = GLYPHS[ch.toUpperCase()];
  return g ? g.split('|') : null;
}

export function textWidth(str: string, scale: number): number {
  return str.length === 0 ? 0 : (str.length * (GLYPH_W + 1) - 1) * scale;
}
